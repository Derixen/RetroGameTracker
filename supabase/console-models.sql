-- Run in Supabase SQL Editor before using the Console Models feature.
create table if not exists public.console_models (
  id bigint generated by default as identity primary key,
  platform_id bigint not null references public.platforms(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  model_name text not null check (length(trim(model_name)) between 1 and 120),
  model_number text,
  condition text check (condition in ('New','Excellent','Good','Fair','For parts')),
  ownership_status text not null default 'owned' check (ownership_status in ('owned','wishlist','previously_owned')),
  image_url text,
  image_path text,
  notes text,
  created_at timestamptz not null default now()
);
create index if not exists console_models_user_platform_idx on public.console_models(user_id, platform_id);
alter table public.console_models enable row level security;
drop policy if exists "Users can read own console models" on public.console_models;
create policy "Users can read own console models" on public.console_models for select to authenticated using (user_id = (select auth.uid()));
drop policy if exists "Users can add own console models" on public.console_models;
create policy "Users can add own console models" on public.console_models for insert to authenticated with check (user_id = (select auth.uid()));
drop policy if exists "Users can update own console models" on public.console_models;
create policy "Users can update own console models" on public.console_models for update to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
drop policy if exists "Users can delete own console models" on public.console_models;
create policy "Users can delete own console models" on public.console_models for delete to authenticated using (user_id = (select auth.uid()));

-- Private bucket: uploaded console images must never be publicly readable.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('console-images','console-images',false,5242880,array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public=false, file_size_limit=5242880, allowed_mime_types=array['image/jpeg','image/png','image/webp'];

-- Files stored as <auth.uid()>/<random-uuid>.<extension>.
drop policy if exists "Console owners can read images" on storage.objects;
create policy "Console owners can read images" on storage.objects for select to authenticated using (bucket_id = 'console-images' and (storage.foldername(name))[1] = (select auth.uid())::text);
drop policy if exists "Console owners can upload images" on storage.objects;
create policy "Console owners can upload images" on storage.objects for insert to authenticated with check (bucket_id = 'console-images' and (storage.foldername(name))[1] = (select auth.uid())::text);
drop policy if exists "Console owners can delete images" on storage.objects;
create policy "Console owners can delete images" on storage.objects for delete to authenticated using (bucket_id = 'console-images' and (storage.foldername(name))[1] = (select auth.uid())::text);
